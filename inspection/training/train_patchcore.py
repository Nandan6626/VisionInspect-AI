"""
PatchCore Industrial Training Pipeline using Anomalib.
Learns normal industrial component representations using Wide ResNet-50-2
and builds an efficient coreset memory bank for anomaly detection.
"""
import os
import json
import shutil
import argparse
from pathlib import Path
import torch

from anomalib.models import Patchcore
from anomalib.engine import Engine
from anomalib.data import Folder


def train_patchcore(
    dataset_root: str = "datasets/mvtec_grid",
    category_name: str = "grid",
    output_dir: str = "models/patchcore",
    backbone: str = "wide_resnet50_2",
    coreset_ratio: float = 0.1,
    batch_size: int = 4
):
    print("=" * 65)
    print(" VISIONINSPECT AI – PATCHCORE INDUSTRIAL TRAINING")
    print("=" * 65)
    print(f"Dataset Root:      {dataset_root}")
    print(f"Category:          {category_name}")
    print(f"Feature Backbone:  {backbone}")
    print(f"Coreset Ratio:     {coreset_ratio}")
    print(f"Output Directory:  {output_dir}")
    print("=" * 65)

    os.makedirs(output_dir, exist_ok=True)
    normal_dir = os.path.join(dataset_root, "train", "good")
    normal_test_dir = os.path.join(dataset_root, "test", "good")
    defect_dir = os.path.join(dataset_root, "test", "defect")

    if not os.path.exists(normal_dir) or len(os.listdir(normal_dir)) == 0:
        raise FileNotFoundError(
            f"Normal training directory '{normal_dir}' is empty or does not exist. "
            "Please run prepare_dataset.py first."
        )

    # 1. Setup DataModule
    print("\n[Step 1/4] Configuring Industrial DataModule...")
    datamodule = Folder(
        name=category_name,
        root=dataset_root,
        normal_dir="train/good",
        normal_test_dir="test/good",
        abnormal_dir="test/defect",
        train_batch_size=batch_size,
        eval_batch_size=batch_size,
        num_workers=0,  # Windows safe
    )

    # 2. Instantiate PatchCore Model
    print("\n[Step 2/4] Initializing PatchCore Architecture...")
    model = Patchcore(
        backbone=backbone,
        layers=("layer2", "layer3"),
        coreset_sampling_ratio=coreset_ratio,
        pre_trained=True,
    )

    # 3. Fit Memory Bank
    print("\n[Step 3/4] Building Patch Memory Bank via Coreset Subsampling...")
    engine_temp_dir = os.path.join(output_dir, "_engine_work")
    os.makedirs(engine_temp_dir, exist_ok=True)

    engine = Engine(
        default_root_dir=engine_temp_dir,
        max_epochs=1,
    )
    engine.fit(model=model, datamodule=datamodule)

    # 4. Save Final Weights & Metadata
    print("\n[Step 4/4] Exporting Checkpoint and Configuration...")
    # Find generated checkpoint in engine_temp_dir
    found_ckpts = list(Path(engine_temp_dir).rglob("*.ckpt"))
    if not found_ckpts:
        raise RuntimeError("No checkpoint file generated by Anomalib Engine.")

    final_ckpt_path = os.path.join(output_dir, "patchcore_model.ckpt")
    shutil.copy2(str(found_ckpts[0]), final_ckpt_path)

    # Compute anomaly threshold heuristic (default 0.5)
    config = {
        "model_type": "PatchCore",
        "framework": "Anomalib",
        "backbone": backbone,
        "layers": ["layer2", "layer3"],
        "coreset_sampling_ratio": coreset_ratio,
        "category": category_name,
        "dataset_root": dataset_root,
        "anomaly_threshold": 0.5,
        "weights_file": "patchcore_model.ckpt",
    }

    config_path = os.path.join(output_dir, "config.json")
    with open(config_path, "w") as f:
        json.dump(config, f, indent=4)

    # Clean up temp engine logs
    try:
        shutil.rmtree(engine_temp_dir)
    except Exception:
        pass

    print("\n" + "=" * 65)
    print(" PATCHCORE TRAINING COMPLETED SUCCESSFULLY!")
    print(f" Model Weights: {final_ckpt_path}")
    print(f" Config File:   {config_path}")
    print("=" * 65)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Train PatchCore for Industrial Inspection")
    parser.add_argument("--dataset_root", type=str, default="datasets/mvtec_grid")
    parser.add_argument("--category", type=str, default="grid")
    parser.add_argument("--output_dir", type=str, default="models/patchcore")
    parser.add_argument("--backbone", type=str, default="wide_resnet50_2")
    parser.add_argument("--coreset_ratio", type=float, default=0.1)
    parser.add_argument("--batch_size", type=int, default=4)




    
    args = parser.parse_args()
    train_patchcore(
        dataset_root=args.dataset_root,
        category_name=args.category,
        output_dir=args.output_dir,
        backbone=args.backbone,
        coreset_ratio=args.coreset_ratio,
        batch_size=args.batch_size,
    )
